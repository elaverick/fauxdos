    .byte "SENSOR ","3      ","45     ","135    ","HOLD   ","KAI    ","EAST   ","C-207  "
    .byte "DRONE  ","1      ","210    ","210    ","READY  ","MIRA   ","NORTH  ","D-031  "
    .fill 896-280,32
