OS_LOAD=$F20C
OS_PUTCHAR=$F200
ARG_LO=$06
ARG_HI=$07
PTR_LO=$00
PTR_HI=$01
DATA_LO=$02
DATA_HI=$03
SIZE_LO=$08
SIZE_HI=$09
.org $4000
START:
    LDY #$00
    LDA (ARG_LO),Y
    BEQ USAGE
    LDA ARG_LO
    STA PTR_LO
    LDA ARG_HI
    STA PTR_HI
    LDA #$00
    STA DATA_LO
    LDA #$50
    STA DATA_HI
    JSR OS_LOAD
    BCS FILE_NOT_FOUND
PRINT_NEXT:
    LDA SIZE_LO
    ORA SIZE_HI
    BEQ PRINT_DONE
    LDY #$00
    LDA (DATA_LO),Y
    JSR OS_PUTCHAR
    INC DATA_LO
    BNE PTR_INCREMENTED
    INC DATA_HI
PTR_INCREMENTED:
    LDA SIZE_LO
    BNE DEC_SIZE_LOW
    DEC SIZE_HI
DEC_SIZE_LOW:
    DEC SIZE_LO
    JMP PRINT_NEXT
PRINT_DONE:
    LDA #$0D
    JSR OS_PUTCHAR
    RTS
USAGE:
    LDA #<USAGE_TEXT
    STA PTR_LO
    LDA #>USAGE_TEXT
    STA PTR_HI
    JSR $F203
    RTS
FILE_NOT_FOUND:
    LDA #<ERROR_TEXT
    STA PTR_LO
    LDA #>ERROR_TEXT
    STA PTR_HI
    JSR $F203
    RTS
ERROR_TEXT:
    .byte "? FILE NOT FOUND",$0D,0
USAGE_TEXT:
    .byte "USAGE: CAT NAME",$0D,0
