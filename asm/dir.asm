OS_DIR=$F209
OS_PUTCHAR=$F200
DIR_BUFFER=$0300
RECORD_SIZE=20
PTR_LO=$02
PTR_HI=$03
COUNT=$0A
.org $4000
START:
    JSR OS_DIR
    STA COUNT
    LDA #<DIR_BUFFER
    STA PTR_LO
    LDA #>DIR_BUFFER
    STA PTR_HI
    LDX #$00
NEXT_ENTRY:
    CPX COUNT
    BEQ DONE
    LDY #$00
NEXT_CHAR:
    LDA (PTR_LO),Y
    BEQ END_NAME
    JSR OS_PUTCHAR
    INY
    JMP NEXT_CHAR
END_NAME:
    LDY #$12
    LDA (PTR_LO),Y
    AND #$02
    BEQ ENTRY_IS_FILE
    LDA #'/'
    JSR OS_PUTCHAR
ENTRY_IS_FILE:
    LDA #$0D
    JSR OS_PUTCHAR
    CLC
    LDA PTR_LO
    ADC #RECORD_SIZE
    STA PTR_LO
    LDA PTR_HI
    ADC #$00
    STA PTR_HI
    INX
    JMP NEXT_ENTRY
DONE:
    RTS
